"""Data schemas for the Hy3 Code Process Eval system."""

from __future__ import annotations

from enum import Enum
from typing import Any, Optional

from pydantic import BaseModel, Field


# =============================================================================
# Error Type Taxonomy
# =============================================================================


class ErrorType(str, Enum):
    """Standardized error types for process evaluation."""

    FORMAT_ERROR = "FORMAT_ERROR"  # Output format does not match requirements
    SPEC_MISREAD = "SPEC_MISREAD"  # Problem specification misunderstood
    CONDITION_MISSING = "CONDITION_MISSING"  # Edge case or condition not handled
    UNJUSTIFIED_ASSUMPTION = "UNJUSTIFIED_ASSUMPTION"  # Assumption without basis
    ALGORITHM_INVALID = "ALGORITHM_INVALID"  # Algorithm choice is fundamentally wrong
    REASONING_GAP = "REASONING_GAP"  # Logical gap in reasoning chain
    COMPLEXITY_MISCLAIM = "COMPLEXITY_MISCLAIM"  # Complexity claim contradicts implementation
    EDGE_CASE_FAILURE = "EDGE_CASE_FAILURE"  # Failure on edge/boundary inputs
    PLAN_CODE_MISMATCH = "PLAN_CODE_MISMATCH"  # Implementation does not match plan
    PROCESS_RESULT_MISMATCH = "PROCESS_RESULT_MISMATCH"  # Correct result but flawed process
    RUNTIME_ERROR = "RUNTIME_ERROR"  # Code raises exception during execution
    TIMEOUT = "TIMEOUT"  # Code exceeds time limit
    SECURITY_VIOLATION = "SECURITY_VIOLATION"  # Security issue in code
    UNKNOWN = "UNKNOWN"  # Unclassified error


class StepId(str, Enum):
    """The seven standard problem-solving steps."""

    S1_REQUIREMENT_UNDERSTANDING = "S1"  # Requirement understanding
    S2_CONSTRAINTS_AND_EDGES = "S2"  # Constraints and edge cases
    S3_ALGORITHM_CHOICE = "S3"  # Algorithm selection
    S4_CORRECTNESS_ARGUMENT = "S4"  # Correctness proof/argument
    S5_COMPLEXITY_ANALYSIS = "S5"  # Complexity analysis
    S6_SELF_TEST_PLAN = "S6"  # Self-test plan
    S7_CODE_IMPLEMENTATION = "S7"  # Code implementation


# =============================================================================
# Core Data Structures
# =============================================================================


class Clause(BaseModel):
    """A specification clause extracted from the problem statement."""

    id: str = Field(..., description="Clause identifier, e.g., C1, C2")
    text: str = Field(..., description="Natural language description of the clause")


class ProcessStep(BaseModel):
    """A single step in the Hy3-generated solution process."""

    id: str = Field(..., description="Step identifier (S1-S7)")
    type: str = Field(..., description="Step type name")
    claim: str = Field(..., description="The claim or content of this step")
    related_clauses: list[str] = Field(
        default_factory=list, description="IDs of related specification clauses"
    )


class ComplexityClaim(BaseModel):
    """Time and space complexity claims."""

    time: str = Field(default="unknown", description="Time complexity, e.g., O(n)")
    space: str = Field(default="unknown", description="Space complexity, e.g., O(n)")


class ProblemSpec(BaseModel):
    """Unified problem specification from any supported dataset."""

    task_id: str = Field(..., description="Unique problem identifier")
    dataset: str = Field(..., description="Source dataset name, e.g., mbppplus")
    difficulty: str = Field(default="medium", description="Difficulty level")
    prompt: str = Field(..., description="Problem description / prompt text")
    entry_point: str = Field(..., description="Function name to implement")
    canonical_solution: str = Field(..., description="Reference/canonical solution code")
    base_tests: list[str] = Field(
        default_factory=list, description="Base test assertions (original)"
    )
    plus_tests: list[str] = Field(
        default_factory=list, description="Enhanced test assertions (EvalPlus)"
    )
    clauses: list[Clause] = Field(
        default_factory=list, description="Extracted specification clauses"
    )


class SolutionRecord(BaseModel):
    """Complete solution record generated by Hy3 solver."""

    task_id: str = Field(..., description="Associated problem ID")
    steps: list[ProcessStep] = Field(
        default_factory=list, description="S1-S7 process steps"
    )
    complexity: ComplexityClaim = Field(
        default_factory=ComplexityClaim, description="Complexity analysis"
    )
    code: str = Field(..., description="Generated Python function code")
    raw_response: Optional[str] = Field(
        default=None, description="Raw Hy3 response text (for debugging)"
    )
    generation_time_ms: Optional[int] = Field(
        default=None, description="Generation latency in milliseconds"
    )
    parse_error: Optional[str] = Field(
        default=None, description="Error message if parsing failed"
    )


class EvidenceRecord(BaseModel):
    """A piece of evidence for or against the solution's correctness."""

    source: str = Field(
        ...,
        description="Evidence source: plus_test, static_check, sbfl, hy3_review, base_test",
    )
    status: str = Field(
        ...,
        description="Evidence status: verified, contradicted, insufficient, warning",
    )
    detail: str = Field(..., description="Human-readable detail of this evidence")
    target_step: Optional[str] = Field(
        default=None, description="Target step ID this evidence relates to (S1-S7)"
    )
    target_clause: Optional[str] = Field(
        default=None, description="Target clause ID this evidence relates to"
    )
    error_type: Optional[ErrorType] = Field(
        default=None, description="Error type if this evidence indicates an error"
    )
    confidence: float = Field(
        default=1.0, ge=0.0, le=1.0, description="Confidence score for this evidence"
    )
    metadata: dict[str, Any] = Field(
        default_factory=dict, description="Additional metadata"
    )


class SuspectCodeLine(BaseModel):
    """A suspicious code line identified by SBFL."""

    line: int = Field(..., description="Line number (1-based)")
    score: float = Field(..., ge=0.0, le=1.0, description="Suspiciousness score (Ochiai)")
    reason: str = Field("", description="Explanation of why this line is suspicious")


class EvaluationResult(BaseModel):
    """Complete evaluation result for a single problem."""

    task_id: str = Field(..., description="Problem identifier")
    dataset: str = Field(..., description="Source dataset")

    # Final correctness
    final_correct: bool = Field(
        default=False, description="Whether the solution passes all tests"
    )
    base_passed: bool = Field(
        default=False, description="Whether base tests pass"
    )
    plus_passed: bool = Field(
        default=False, description="Whether enhanced tests pass"
    )

    # Process assessment
    process_correct: bool = Field(
        default=False, description="Whether the reasoning process is valid"
    )
    first_error_step: Optional[str] = Field(
        default=None, description="First step where error appears (S1-S7)"
    )
    violated_clause: Optional[str] = Field(
        default=None, description="ID of the primary violated clause"
    )
    primary_error_type: ErrorType = Field(
        default=ErrorType.UNKNOWN, description="Primary error classification"
    )
    unsupported_success: bool = Field(
        default=False,
        description="True if final answer correct but process cannot support it",
    )

    # Code-level localization
    suspect_code_lines: list[SuspectCodeLine] = Field(
        default_factory=list, description="SBFL-identified suspicious lines"
    )

    # Evidence collection
    evidence: list[EvidenceRecord] = Field(
        default_factory=list, description="All collected evidence records"
    )

    # Execution details
    total_tests: int = Field(default=0, description="Total number of tests run")
    passed_tests: int = Field(default=0, description="Number of tests passed")
    failed_tests: int = Field(default=0, description="Number of tests failed")
    execution_errors: int = Field(default=0, description="Number of runtime errors")

    # Timing
    eval_time_ms: Optional[int] = Field(
        default=None, description="Total evaluation time in milliseconds"
    )


class MetricsSummary(BaseModel):
    """Aggregated metrics across all evaluated problems."""

    total_problems: int = 0
    final_accuracy: float = 0.0  # final_correct / total
    base_pass_rate: float = 0.0
    plus_pass_rate: float = 0.0
    process_accuracy: float = 0.0  # process_correct / total

    # Error localization metrics
    unsupported_success_count: int = 0
    unsupported_success_rate: float = 0.0

    # Error type distribution
    error_type_distribution: dict[str, int] = Field(default_factory=dict)

    # Difficulty breakdown
    difficulty_breakdown: dict[str, dict[str, Any]] = Field(default_factory=dict)

    # Validation metrics (if ground truth available)
    localization_accuracy: Optional[float] = None
    false_positive_rate: Optional[float] = None
    error_type_accuracy: Optional[float] = None

    # Metadata
    dataset_name: str = ""
    sample_size: int = 0
    model_name: str = ""
    timestamp: str = ""
